import Foundation
import SwitcherCore

/// Opens Terminal windows that run generated `.command` scripts (login flows, "open terminal with account").
/// `.command` files need no Apple-events permission and run in the user's own Terminal.
public struct TerminalLauncher: Sendable {
    public let paths: SwitcherPaths
    public let profiles: CLIProfileManager
    /// "Terminal" (default) or e.g. "iTerm".
    public var terminalApp: String

    public init(paths: SwitcherPaths, profiles: CLIProfileManager, terminalApp: String = "Terminal") {
        self.paths = paths
        self.profiles = profiles
        self.terminalApp = terminalApp
    }

    public func writeCommandFile(name: String, script: String) throws -> URL {
        try FileManager.default.createDirectory(at: paths.tmp, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
        let safe = CLIProfileManager.slug(name)
        let url = paths.tmp.appendingPathComponent("\(safe)-\(UUID().uuidString.prefix(8)).command")
        try AtomicFile.write(script, to: url, permissions: 0o700)
        return url
    }

    public func open(_ url: URL) throws {
        let r = try ProcessRunner().run("/usr/bin/open", arguments: ["-a", terminalApp, url.path], environment: nil, currentDirectory: nil, input: nil, timeout: 20)
        if r.exitCode != 0 {
            // Fall back to the default handler for .command files.
            let r2 = try ProcessRunner().run("/usr/bin/open", arguments: [url.path], environment: nil, currentDirectory: nil, input: nil, timeout: 20)
            guard r2.exitCode == 0 else { throw NSError(domain: "TerminalLauncher", code: Int(r2.exitCode), userInfo: [NSLocalizedDescriptionKey: SwitcherLog.redact(r2.stderr)]) }
        }
        SwitcherLog.shared.log("opened terminal for \(url.lastPathComponent)", category: "terminal")
    }

    /// Runs a provider login script in a new Terminal window.
    @discardableResult
    public func runLogin(script: String, account: Account) throws -> URL {
        let url = try writeCommandFile(name: "login-\(account.provider.rawValue)-\(account.name)", script: script)
        try open(url)
        return url
    }

    /// Opens an interactive shell whose `claude`/`codex` use this account, regardless of the global selection.
    /// Works with the wrapper (AISWITCH_*_PROFILE) and without it (direct config-dir export).
    @discardableResult
    public func openShell(for account: Account, shellPath: String?) throws -> URL {
        var lines = ["#!/bin/bash", "# Generated by AI Account Switcher: terminal bound to \(ShellQuote.single(account.name))", ""]
        lines.append("export \(account.provider.profileOverrideEnvVar)=\(ShellQuote.single(account.id))")
        for (k, v) in profiles.environmentOverrides(for: account) { lines.append("export \(k)=\(ShellQuote.single(v))") }
        lines.append("cd \"$HOME\"")
        lines.append("echo \"This terminal uses the \(account.provider.displayName) account '\(account.name)' (profile \(account.id)).\"")
        let shell = shellPath ?? ProcessInfo.processInfo.environment["SHELL"] ?? "/bin/zsh"
        lines.append("exec \(ShellQuote.single(shell)) -l")
        let url = try writeCommandFile(name: "shell-\(account.provider.rawValue)-\(account.name)", script: lines.joined(separator: "\n") + "\n")
        try open(url)
        return url
    }

    /// Resumes a stored conversation in a new Terminal window bound to `account`: cd to the session's original
    /// folder (Claude Code looks the transcript up there), run the vendor CLI with its resume arguments, then
    /// leave an interactive shell bound to the same account.
    @discardableResult
    public func openResume(session: CLISession, account: Account, executable: String, shellPath: String?) throws -> URL {
        var lines = ["#!/bin/bash", "# Generated by AI Account Switcher: resume \(session.provider.displayName) session \(session.id) under \(ShellQuote.single(account.name))", ""]
        lines.append("export \(account.provider.profileOverrideEnvVar)=\(ShellQuote.single(account.id))")
        for (k, v) in profiles.environmentOverrides(for: account) { lines.append("export \(k)=\(ShellQuote.single(v))") }
        lines.append("unset " + account.provider.credentialOverrideEnvVars.joined(separator: " "))
        lines.append("if ! cd \(ShellQuote.single(session.cwd)) 2>/dev/null; then echo \"Original folder \(session.cwd) no longer exists; starting in $HOME\"; cd \"$HOME\"; fi")
        lines.append("echo \"== AI Account Switcher: resuming session \(session.id) under '\(account.name)' ==\"")
        lines.append("echo \"Title: \(ShellQuote.single(session.title))\"")
        lines.append("\(ShellQuote.single(executable)) " + session.resumeArguments.map(ShellQuote.single).joined(separator: " "))
        lines.append("echo; echo \"Session ended. This shell stays bound to '\(account.name)'.\"")
        let shell = shellPath ?? ProcessInfo.processInfo.environment["SHELL"] ?? "/bin/zsh"
        lines.append("exec \(ShellQuote.single(shell)) -l")
        let url = try writeCommandFile(name: "resume-\(account.provider.rawValue)-\(account.name)", script: lines.joined(separator: "\n") + "\n")
        try open(url)
        return url
    }

    /// Removes generated .command files older than a day.
    public func cleanup(olderThan age: TimeInterval = 86_400) {
        let fm = FileManager.default
        guard let items = try? fm.contentsOfDirectory(at: paths.tmp, includingPropertiesForKeys: [.contentModificationDateKey]) else { return }
        for item in items where item.pathExtension == "command" {
            if let date = (try? item.resourceValues(forKeys: [.contentModificationDateKey]))?.contentModificationDate,
               Date().timeIntervalSince(date) > age {
                try? fm.removeItem(at: item)
            }
        }
    }
}
