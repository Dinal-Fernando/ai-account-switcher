import Foundation

public struct CodexProvider: ProviderAdapter {
    public static let usageURL = URL(string: "https://chatgpt.com/backend-api/wham/usage")!

    public let provider: Provider = .codex
    public let context: ProviderContext

    public init(context: ProviderContext) { self.context = context }

    public func checkAuth(account: Account) async -> AuthStatus {
        let now = context.time.now
        guard let exe = executablePath() else {
            return AuthStatus(state: .error, message: "codex executable not found", checkedAt: now)
        }
        do {
            let r = try await context.runner.runAsync(exe, arguments: ["login", "status"], environment: context.cliEnvironment(for: account), timeout: 60)
            var status = CodexAuthParser.parseLoginStatus(r, now: now)
            if status.isAuthenticated, let setting = credentialStoreSetting(account: account), setting != "file", setting != "auto" {
                status.warnings.append("cli_auth_credentials_store = \"\(setting)\": credentials live in the OS keyring (keyed by this CODEX_HOME), so switching still works but the usage dashboard cannot read them.")
            }
            return status
        } catch {
            return AuthStatus(state: .error, message: SwitcherLog.redact(error.localizedDescription), checkedAt: now)
        }
    }

    func credentialStoreSetting(account: Account) -> String? {
        guard let toml = try? String(contentsOf: context.profiles.codexConfigFile(for: account), encoding: .utf8) else { return nil }
        return CLIProfileManager.codexCredentialStoreSetting(in: toml)
    }

    func readAuthFile(account: Account) -> CodexAuthFile? {
        guard let data = try? Data(contentsOf: context.profiles.codexAuthFile(for: account)) else { return nil }
        return CodexAuthParser.parseAuthFile(data)
    }

    public func identity(account: Account) -> AccountIdentity? {
        guard let auth = readAuthFile(account: account) else { return nil }
        return CodexAuthParser.identity(from: auth, now: context.time.now)
    }

    public func loginScript(account: Account, deviceAuth: Bool) -> String? {
        guard let exe = executablePath() else { return nil }
        var lines = ["#!/bin/bash", "# Generated by AI Account Switcher: sign in to the Codex profile \(ShellQuote.single(account.name)).", ""]
        for (k, v) in context.profiles.environmentOverrides(for: account) { lines.append("export \(k)=\(ShellQuote.single(v))") }
        lines.append("unset " + provider.credentialOverrideEnvVars.joined(separator: " "))
        lines.append("echo \"== AI Account Switcher: Codex profile '\(account.name)' ==\"")
        lines.append("echo \"CODEX_HOME: \(context.profiles.configDirectory(for: account).path)\"")
        if deviceAuth {
            lines.append("echo \"Device-code login: open the printed URL on any device and enter the code.\"; echo")
            lines.append("\(ShellQuote.single(exe)) login --device-auth")
        } else {
            lines.append("echo \"A browser window will open for the ChatGPT login. Finish it, then return here.\"; echo")
            lines.append("\(ShellQuote.single(exe)) login")
        }
        lines.append("code=$?")
        lines.append("echo; if [ $code -eq 0 ]; then echo \"Login finished. You can close this window and go back to AI Account Switcher.\"; else echo \"codex login exited with status $code.\"; fi")
        lines.append("exit $code")
        return lines.joined(separator: "\n") + "\n"
    }

    public func fetchUsage(account: Account) async throws -> UsageSnapshot {
        guard account.usageSource == .cliLogin else { throw UsageFetchError.disabled }
        if let setting = credentialStoreSetting(account: account), setting != "file", setting != "auto" {
            throw UsageFetchError.unsupported("This profile keeps its login in the system keyring (credential store: \(setting)), which the usage monitor cannot read. Switch the profile to file storage to see its quota.")
        }
        guard let auth = readAuthFile(account: account) else {
            throw UsageFetchError.noCredential("No Codex login found for this profile (auth.json missing). Sign in first.")
        }
        guard let token = auth.accessToken, !token.isEmpty else {
            if auth.apiKey != nil { throw UsageFetchError.unsupported("This profile uses an OpenAI API key; there is no ChatGPT plan quota to show.") }
            throw UsageFetchError.noCredential("No ChatGPT login found for this profile. Sign in first.")
        }
        let now = context.time.now
        if let exp = JWT.expiry(token), exp.timeIntervalSince(now) < 60 {
            throw UsageFetchError.credentialExpired("This account has not been used for a while, so its Codex usage token lapsed. Codex renews it the next time you use the account.")
        }
        var headers = ["Authorization": "Bearer \(token)", "Accept": "application/json", "User-Agent": context.userAgent]
        let accountId = auth.accountId ?? account.identity?.accountId
        if let accountId, !accountId.isEmpty { headers["chatgpt-account-id"] = accountId }
        let response: HTTPResponse
        do {
            response = try await context.http.get(Self.usageURL, headers: headers, timeout: 30)
        } catch {
            throw UsageFetchError.network(error.localizedDescription)
        }
        if let err = classify(response) { throw err }
        let decoded: CodexUsageResponse
        do { decoded = try CodexUsageDecoder.decode(response.body) } catch {
            throw UsageFetchError.decoding("Unexpected usage payload: \(error.localizedDescription)")
        }
        guard var snapshot = CodexUsageDecoder.snapshot(from: decoded, accountId: account.id, now: context.time.now) else {
            throw UsageFetchError.unsupported("No rate-limit windows were returned for this account.")
        }
        if snapshot.plan == nil { snapshot.plan = account.identity?.plan }
        return snapshot
    }

    public func compatibilityIssues(version: String?, account: Account?) -> [CompatibilityIssue] {
        var issues: [CompatibilityIssue] = []
        if version == nil {
            issues.append(CompatibilityIssue(id: "codex-version-unknown", severity: .warning, title: "Codex version unknown",
                                             detail: "Could not run codex --version. CODEX_HOME isolation is documented for current releases."))
        }
        if let account, let setting = credentialStoreSetting(account: account), setting == "ephemeral" {
            issues.append(CompatibilityIssue(id: "codex-ephemeral", severity: .blocking, title: "Ephemeral credential store",
                                             detail: "cli_auth_credentials_store = \"ephemeral\" keeps logins in memory only; this profile will ask you to sign in on every launch."))
        }
        return issues
    }
}
