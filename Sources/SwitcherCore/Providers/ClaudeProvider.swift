import Foundation

/// Reads a Claude Code credential payload. On macOS the vendor stores it in the login Keychain under a
/// service name derived from CLAUDE_CONFIG_DIR; `security(1)` is the same tool Claude Code itself uses,
/// so no additional Keychain ACL prompts are expected. Read-only: nothing is ever written back.
public struct ClaudeCredentialReader: Sendable {
    let context: ProviderContext

    public init(context: ProviderContext) { self.context = context }

    public func read(account: Account) -> ClaudeAuthStatusParser.Credential? {
        let service = context.profiles.claudeKeychainService(for: account)
        let user = CLIProfileManager.claudeKeychainAccount(environment: context.baseEnvironment)
        if FileManager.default.isExecutableFile(atPath: "/usr/bin/security") {
            if let r = try? context.runner.run("/usr/bin/security", arguments: ["find-generic-password", "-s", service, "-a", user, "-w"],
                                               environment: nil, currentDirectory: nil, input: nil, timeout: 15),
               r.exitCode == 0, let cred = ClaudeAuthStatusParser.credential(fromCredentialsJSON: Data(r.stdout.trimmingCharacters(in: .whitespacesAndNewlines).utf8)) {
                return cred
            }
        }
        let file = context.profiles.claudeCredentialsFile(for: account)
        if let data = try? Data(contentsOf: file), let cred = ClaudeAuthStatusParser.credential(fromCredentialsJSON: data) {
            return cred
        }
        return nil
    }
}

public struct ClaudeProvider: ProviderAdapter {
    public static let usageURL = URL(string: "https://api.anthropic.com/api/oauth/usage")!
    public static let betaHeader = "oauth-2025-04-20"
    /// `claude auth status --json` gained `configDirectory` in this version; we use it to prove the profile was honoured.
    public static let minimumVerifiedVersion = VersionNumber([2, 1, 268])
    /// Before this version a short command such as `auth status` could exit in the middle of a token renewal.
    public static let tokenRefreshFixedVersion = VersionNumber([2, 1, 301])
    public static let pausedMessage = "This account has not been used for a while, so its usage token lapsed. Claude Code renews it the next time you use the account; Refresh now asks it to renew right away."


    public let provider: Provider = .claude
    public let context: ProviderContext

    public init(context: ProviderContext) { self.context = context }

    public func checkAuth(account: Account) async -> AuthStatus {
        let now = context.time.now
        guard let exe = executablePath() else {
            return AuthStatus(state: .error, message: "claude executable not found", checkedAt: now)
        }
        let env = context.cliEnvironment(for: account)
        let expectedDir = context.profiles.configDirectory(for: account).path
        do {
            let r = try await context.runner.runAsync(exe, arguments: ["auth", "status"], environment: env, timeout: 90)
            let parsed = ClaudeAuthStatusParser.parse(r.stdout) ?? ClaudeAuthStatusParser.parse(r.combinedOutput)
            var status = ClaudeAuthStatusParser.authStatus(from: parsed, result: r, isManagedProfile: !account.isDefault, expectedConfigDir: expectedDir, now: now)
            if status.isAuthenticated, (parsed?.configDirectory ?? "").isEmpty {
                status.warnings.append("This Claude Code version does not report its config directory (needs ≥ \(Self.minimumVerifiedVersion)); profile isolation could not be verified automatically.")
            }
            return status
        } catch {
            return AuthStatus(state: .error, message: SwitcherLog.redact(error.localizedDescription), checkedAt: now)
        }
    }

    public func identity(account: Account) -> AccountIdentity? {
        let file = context.profiles.claudeGlobalConfigFile(for: account)
        guard let data = try? Data(contentsOf: file) else { return nil }
        return ClaudeAuthStatusParser.identity(fromGlobalConfig: data)
    }

    public func loginScript(account: Account, deviceAuth: Bool) -> String? {
        guard let exe = executablePath() else { return nil }
        var lines = ["#!/bin/bash", "# Generated by AI Account Switcher: sign in to the Claude Code profile \(ShellQuote.single(account.name)).", ""]
        for (k, v) in context.profiles.environmentOverrides(for: account) { lines.append("export \(k)=\(ShellQuote.single(v))") }
        lines.append("unset " + provider.credentialOverrideEnvVars.joined(separator: " "))
        lines.append("export DISABLE_AUTOUPDATER=1")
        lines.append("echo \"== AI Account Switcher: Claude Code profile '\(account.name)' ==\"")
        lines.append("echo \"Config dir: \(context.profiles.configDirectory(for: account).path)\"")
        lines.append("echo \"A browser window will open for the claude.ai login. Finish it, then return here.\"; echo")
        lines.append("\(ShellQuote.single(exe)) auth login")
        lines.append("code=$?")
        lines.append("echo; if [ $code -eq 0 ]; then echo \"Login finished. You can close this window and go back to AI Account Switcher.\"; else echo \"claude auth login exited with status $code.\"; fi")
        lines.append("exit $code")
        return lines.joined(separator: "\n") + "\n"
    }

    public func fetchUsage(account: Account) async throws -> UsageSnapshot {
        guard account.usageSource == .cliLogin else { throw UsageFetchError.disabled }
        if let auth = account.lastAuth, auth.isAuthenticated, let m = auth.method, m == "api_key" || m == "api_key_helper" || m == "third_party" {
            throw UsageFetchError.unsupported("This profile does not use a claude.ai subscription, so there is no plan quota to show.")
        }
        let reader = ClaudeCredentialReader(context: context)
        var credential = reader.read(account: account)
        let now = context.time.now
        if credential == nil {
            throw UsageFetchError.noCredential("No claude.ai login found for this profile. Sign in first.")
        }
        if let c = credential, c.isExpired(now: now) {
            // Let Claude Code renew its own token (auth status triggers the vendor's refresh path on ≥ 2.1.301).
            guard await refreshCredential(account: account) else {
                throw UsageFetchError.credentialExpired(Self.pausedMessage)
            }
            credential = reader.read(account: account)
        }
        guard let token = credential?.accessToken else { throw UsageFetchError.noCredential("No claude.ai login found for this profile.") }
        let headers = ["Authorization": "Bearer \(token)", "anthropic-beta": Self.betaHeader,
                       "Accept": "application/json", "User-Agent": context.userAgent]
        let response: HTTPResponse
        do {
            response = try await context.http.get(Self.usageURL, headers: headers, timeout: 30)
        } catch {
            throw UsageFetchError.network(error.localizedDescription)
        }
        if let err = classify(response) { throw err }
        let decoded: ClaudeUsageResponse
        do { decoded = try ClaudeUsageDecoder.decode(response.body) } catch {
            throw UsageFetchError.decoding("Unexpected usage payload: \(error.localizedDescription)")
        }
        guard var snapshot = ClaudeUsageDecoder.snapshot(from: decoded, accountId: account.id, now: context.time.now) else {
            throw UsageFetchError.unsupported("This plan has no usage dashboard (no 5-hour/weekly windows were returned).")
        }
        snapshot.plan = credential?.subscriptionType ?? account.identity?.plan
        return snapshot
    }

    /// Asks Claude Code to renew the stored token by running `auth status` inside the profile, then re-reads it.
    /// Returns true when a non-expired token is available afterwards. Never touches the Keychain itself.
    public func refreshCredential(account: Account) async -> Bool {
        if let exe = executablePath() {
            _ = try? await context.runner.runAsync(exe, arguments: ["auth", "status"], environment: context.cliEnvironment(for: account), timeout: 120)
        }
        guard let c = ClaudeCredentialReader(context: context).read(account: account) else { return false }
        return !c.isExpired(now: context.time.now)
    }

    /// Latest values observed by Claude Code itself (status-line beacon), if the beacon is installed for this profile.
    public func beaconSnapshot(account: Account) -> UsageSnapshot? {
        let file = context.paths.statusLineBeaconFile(profileId: account.id)
        guard let attrs = try? FileManager.default.attributesOfItem(atPath: file.path),
              let modified = attrs[.modificationDate] as? Date,
              let data = try? Data(contentsOf: file) else { return nil }
        return ClaudeUsageDecoder.snapshot(fromStatusLineJSON: data, accountId: account.id, observedAt: modified)
    }

    public func compatibilityIssues(version: String?, account: Account?) -> [CompatibilityIssue] {
        var issues: [CompatibilityIssue] = []
        guard let version else {
            issues.append(CompatibilityIssue(id: "claude-version-unknown", severity: .warning, title: "Claude Code version unknown",
                                             detail: "Could not run claude --version. Per-profile Keychain isolation is documented for current releases; verify with claude auth status inside each profile."))
            return issues
        }
        if let v = VersionNumber(parsing: version), v < Self.minimumVerifiedVersion {
            issues.append(CompatibilityIssue(id: "claude-version-old", severity: .warning, title: "Claude Code \(v) is older than \(Self.minimumVerifiedVersion)",
                                             detail: "Versions before 2.1.268 do not report configDirectory in claude auth status, so the switcher cannot prove a profile was honoured. Older builds also stored every login under one Keychain item. Update with claude update, or verify isolation manually (docs/TESTING.md)."))
        }
        if let v = VersionNumber(parsing: version), v < Self.tokenRefreshFixedVersion {
            issues.append(CompatibilityIssue(id: "claude-refresh-version", severity: .warning, title: "Claude Code \(v) may not finish token renewals started by short commands",
                                             detail: "Usage monitoring of idle accounts depends on Claude Code renewing their tokens; before 2.1.301 the renewal could be cut off. Update with: claude update"))
        }
        if let account, let auth = account.lastAuth, let m = auth.method, m == "api_key" || m == "api_key_helper" {
            issues.append(CompatibilityIssue(id: "claude-console-login", severity: .warning, title: "Console sign-in is not isolated per profile",
                                             detail: "Claude Code keeps keyless Console sign-ins outside the config directory. Two Console profiles will share one login. Use claude.ai subscription logins for switching."))
        }
        return issues
    }
}
